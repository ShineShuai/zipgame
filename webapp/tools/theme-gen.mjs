// Writes css/themes/<id>.css from src/themes/<id>/theme.json (seeds + vars) and css/theme.css (the base tokens).
//   node tools/theme-gen.mjs            all themes
//   node tools/theme-gen.mjs candy      one theme
//   node tools/theme-gen.mjs --check    fail when a committed file differs from what would be written
// Prints every contrast nudge (a seed colour that had to move to pass src/themes/schema.js PAIRS) and every problem.
import {
  existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync,
} from 'node:fs';
import { audit, derive, parseBase, validate } from '../src/themes/derive.js';
import { TOKENS } from '../src/themes/schema.js';

const root = new URL('../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const GROUP_TITLES = {
  type: 'type', shape: 'shape and elevation', size: 'sizes', decor: 'page decoration',
  board: 'board numbers and path', icons: 'icon set colours', tiles: 'coloured variant tiles',
};

export function loadThemes() {
  const dirs = readdirSync(new URL('src/themes/', root), { withFileTypes: true }).filter(d => d.isDirectory());
  return dirs
    .filter(d => existsSync(new URL(`src/themes/${d.name}/theme.json`, root)))
    .map(d => JSON.parse(read(`src/themes/${d.name}/theme.json`)));
}

export function build(theme, base) {
  const { tokens, notes } = derive(theme, base);
  const fonts = (theme.fonts ?? []).map(f => f.family);
  const problems = [...validate(theme, tokens, base, fonts), ...audit(tokens).fails];
  const lines = [
    `/* GENERATED by tools/theme-gen.mjs from src/themes/${theme.id}/theme.json. Do not edit. */`,
  ];
  const missingFonts = [];
  for (const f of theme.fonts ?? []) {
    if (existsSync(new URL(`fonts/${f.file}`, root))) {
      lines.push(`@font-face { font-family: "${f.family}"; font-weight: ${f.weight}; font-display: swap;`
        + ` src: url("../../fonts/${f.file}") format("woff2"); }`);
    } else missingFonts.push(f.file);
  }
  lines.push(`:root[data-theme="${theme.id}"] {`, `  color-scheme: ${theme.mode};`);
  const baseNames = Object.keys(base.light);
  for (const name of baseNames) lines.push(`  ${name}: ${tokens[name]};`);
  const byGroup = {};
  for (const [name, spec] of Object.entries(TOKENS)) {
    if (baseNames.includes(name)) continue; // overridable base tokens are already written above
    (byGroup[spec.group] ??= []).push(name);
  }
  for (const [group, names] of Object.entries(byGroup)) {
    lines.push(`  /* ${GROUP_TITLES[group] ?? group} */`);
    for (const name of names) lines.push(`  ${name}: ${tokens[name]};`);
  }
  lines.push('}');
  // caps and tracking have no meaning for CJK text
  if (tokens['--tt-head'] !== 'none' || parseFloat(tokens['--ls-head']) !== 0) {
    lines.push(`:root[lang="zh"][data-theme="${theme.id}"] { --tt-head: none; --ls-head: 0em; }`);
  }
  return { css: `${lines.join('\n')}\n`, notes, problems, missingFonts };
}

if (import.meta.url === new URL(process.argv[1], 'file://').href) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const only = args.filter(a => !a.startsWith('--'));
  const base = parseBase(read('css/theme.css'));
  let bad = 0;
  mkdirSync(new URL('css/themes/', root), { recursive: true });
  for (const theme of loadThemes().filter(t => !only.length || only.includes(t.id))) {
    const { css, notes, problems, missingFonts } = build(theme, base);
    const path = `css/themes/${theme.id}.css`;
    console.log(`${theme.id}: ${notes.length} nudged, ${problems.length} problems, ${css.length} bytes`);
    notes.forEach(n => console.log(`  nudge  ${n}`));
    problems.forEach(p => console.log(`  PROBLEM ${p}`));
    missingFonts.forEach(f => console.log(`  warn   fonts/${f} is not in the repo: the theme falls back to its system stack`));
    if (problems.length) bad++;
    if (check) {
      const had = existsSync(new URL(path, root)) ? read(path) : '';
      if (had !== css) { console.log(`  STALE ${path}: run node tools/theme-gen.mjs`); bad++; }
    } else writeFileSync(new URL(path, root), css);
  }
  process.exit(bad ? 1 : 0);
}
