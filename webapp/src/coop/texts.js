const DICTS = { en: EN, zh: ZH };

export function tx(key, ...args) {
  const text = DICTS[getLang()]?.[key] ?? EN[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (_, index) => args[index]);
}
