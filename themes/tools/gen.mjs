// Writes themes/<id>/theme.css and themes/catalog.json from the sources:
//   themes/<id>/theme.json   seeds + vars + metadata of one theme
//   webapp/src/themes/builtin.js  metadata of the built-in themes (their tokens are webapp/css/theme.css)
//   webapp/css/theme.css     the base tokens every theme starts from
// Usage (from the repo root):
//   node themes/tools/gen.mjs            all themes
//   node themes/tools/gen.mjs candy      one theme (catalog.json is always rewritten)
//   node themes/tools/gen.mjs --check    fail when a committed file differs from what would be written
// Prints every contrast nudge (a seed that had to move to pass schema.js PAIRS) and every problem.
import {
  existsSync, readFileSync, readdirSync, writeFileSync,
} from 'node:fs';
import { audit, derive, parseBase, validate } from './derive.js';
import { BUILTIN } from '../../webapp/src/themes/builtin.js';
import { TOKENS } from './schema.js';

const root = new URL('../', import.meta.url);
export const BASE_CSS = new URL('../../webapp/css/theme.css', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const GROUP_TITLES = {
  type: 'type', shape: 'shape and elevation', size: 'sizes', decor: 'page decoration',
  board: 'board numbers and path', icons: 'icon set colours', tiles: 'coloured variant tiles',
};

export function loadThemes() {
  return readdirSync(root, { withFileTypes: true })
    .filter(d => d.isDirectory() && existsSync(new URL(`${d.name}/theme.json`, root)))
    .map(d => JSON.parse(read(`${d.name}/theme.json`)));
}

export const loadBuiltin = () => BUILTIN;

// The manifest the game fetches (only when the picker or an award/random mechanism needs it): metadata, no tokens.
export function buildCatalog(themes, builtin) {
  const entry = t => ({
    id: t.id, v: t.v, themeApi: t.themeApi, mode: t.mode, name: t.name, chrome: t.chrome ?? t.seeds.bg,
    layout: t.layout, swatches: t.swatches, symbol: t.symbol,
    ...(t.builtin ? { builtin: true } : { art: existsSync(new URL(`${t.id}/art.json`, root)) }),
  });
  return `${JSON.stringify({ themeApi: 1, themes: [...builtin, ...themes].map(entry) }, null, 1)}\n`;
}

export function build(theme, base) {
  const { tokens, notes } = derive(theme, base);
  const fonts = (theme.fonts ?? []).map(f => f.family);
  const problems = [...validate(theme, tokens, base, fonts), ...audit(tokens).fails];
  const lines = [`/* GENERATED by themes/tools/gen.mjs from themes/${theme.id}/theme.json. Do not edit. */`];
  const missingFonts = [];
  for (const f of theme.fonts ?? []) {
    if (existsSync(new URL(`${theme.id}/fonts/${f.file}`, root))) {
      lines.push(`@font-face { font-family: "${f.family}"; font-weight: ${f.weight}; font-display: swap;`
        + ` src: url("fonts/${f.file}") format("woff2"); }`);
    } else missingFonts.push(`${theme.id}/fonts/${f.file}`);
  }
  lines.push(`:root[data-theme="${theme.id}"] {`, `  color-scheme: ${theme.mode};`);
  const baseNames = Object.keys(base.light);
  for (const name of baseNames) lines.push(`  ${name}: ${tokens[name]};`);
  const byGroup = {};
  for (const [name, spec] of Object.entries(TOKENS)) {
    if (baseNames.includes(name)) continue; // already written above
    (byGroup[spec.group] ??= []).push(name);
  }
  for (const [group, names] of Object.entries(byGroup)) {
    lines.push(`  /* ${GROUP_TITLES[group] ?? group} */`);
    for (const name of names) lines.push(`  ${name}: ${tokens[name]};`);
  }
  lines.push('}');
  // caps and tracking have no meaning for CJK text
  if (tokens['--tt-head'] !== 'none' || parseFloat(tokens['--ls-head']) !== 0) {
    lines.push(`:root:lang(zh)[data-theme="${theme.id}"] { --tt-head: none; --ls-head: 0em; }`);
  }
  return { css: `${lines.join('\n')}\n`, notes, problems, missingFonts };
}

if (import.meta.url === new URL(process.argv[1], 'file://').href) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const only = args.filter(a => !a.startsWith('--'));
  const base = parseBase(readFileSync(BASE_CSS, 'utf8'));
  const themes = loadThemes();
  let bad = 0;
  const output = (path, text) => {
    if (check) {
      const had = existsSync(new URL(path, root)) ? read(path) : '';
      if (had !== text) { console.log(`  STALE themes/${path}: run node themes/tools/gen.mjs`); bad++; }
    } else writeFileSync(new URL(path, root), text);
  };
  for (const theme of themes.filter(t => !only.length || only.includes(t.id))) {
    const { css, notes, problems, missingFonts } = build(theme, base);
    console.log(`${theme.id}: ${notes.length} nudged, ${problems.length} problems, ${css.length} bytes`);
    notes.forEach(n => console.log(`  nudge  ${n}`));
    problems.forEach(p => console.log(`  PROBLEM ${p}`));
    missingFonts.forEach(f => console.log(`  warn   themes/${f} is not in the repo: the theme falls back to its system stack`));
    if (problems.length) bad++;
    output(`${theme.id}/theme.css`, css);
  }
  output('catalog.json', buildCatalog(themes, loadBuiltin()));
  process.exit(bad ? 1 : 0);
}
